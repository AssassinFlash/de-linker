#!/usr/bin/env python3
"""#201 migration: the consent surface (docs/specs/201-consent-ga4.md).

Runs against a WordPress through WP-CLI (the pattern of 69-seopress-schema.py):

    python3 tools/migrate/201-consent.py --wp ~/de-linker-local/t201/wp.sh plan
    python3 tools/migrate/201-consent.py --wp ~/de-linker-local/t201/wp.sh \\
        --user <admin> apply --write
    python3 tools/migrate/201-consent.py --wp ~/de-linker-local/t201/wp.sh \\
        --base http://127.0.0.1:9051 verify

What changes, and why it is data rather than code (spec 201):

1. Complianz's own settings (`cmplz_options`): EU rules, the site's own pages
   for the privacy statement and the imprint, no cookie policy document
   generated by the plugin, the cookie database API off, the banner and the
   blocker on, Complianz's own Consent Mode off (Site Kit prints the
   defaults; see `Consent\\Blocking`), and this site's two stated purposes:
   statistics (Google Analytics) and marketing (our own order-source note).
   Every value comes from `tools/migrate/201-consent.json`; the script
   writes it and reads it back.
2. The banner row: first layer with equal weight — Accept all / Reject all
   and a "Choose purposes" step behind them; per-purpose descriptions; the
   site's palette; no close button; the manage-consent tab hidden
   (`hide-everywhere` — the entry point is the site's own footer).
3. The German banner strings, registered by Complianz's own `save()` into
   Polylang (its `icl_register_string`/`wpml_translate_single_string`
   compatibility layer is the plugin's native multilingual path — measured:
   docs/research/2026-10-16/consent-ga4-carrier.md, test 5), then the
   independent German text written into Polylang's string translations.
4. The privacy statement's two sections in both languages: "Cookies" (the
   sentence "We currently use no analytics, advertising, or tracking
   cookies." stops being true the moment GA4 is connected) and "Recipients
   and transfers" (Google joins the processor table).

Not here: the footer's "Cookie settings" entry. That is the LC partial's
markup (`plugins/linker-commerce/content/livecanvas/partials/footer.html` and
its German twin), which `wp linker-commerce present` installs — the same
channel as every other partial change (docs/specs/17-cutover.md, the window
step).

The migration is idempotent: a second run reports nothing to do. A page whose
anchor matches neither the old nor the new shape is refused instead of
guessed at, so a drifted page never gets half of this file written into it.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import urllib.request
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
PLAN_PATH = HERE / "201-consent.json"

# WP-CLI's PHP diagnostics, which must not land in a post's content.
PHP_DIAGNOSTIC = re.compile(
    r"^(PHP (Warning|Notice|Deprecated|Fatal error)|Warning:|Notice:|Deprecated:|Fatal error):"
)

# Writes the options, the banner row and the German strings; prints what it
# changed. `$cmplz_plan` is the decoded JSON, `$cmplz_mode` is plan|apply.
COMPLIANZ_PHP = r"""
$plan = $cmplz_plan;
$mode = $cmplz_mode;
$report = array( 'options' => array(), 'banner' => array(), 'strings' => array(), 'errors' => array() );

// 1. The plugin's settings. Written key by key: keys this file does not name
// (a plugin upgrade may add them) stay as they are.
$current = get_option( 'cmplz_options' );
$current = is_array( $current ) ? $current : array();
$changed = false;
foreach ( $plan['cmplz_options'] as $key => $value ) {
	$same = array_key_exists( $key, $current ) && $current[ $key ] == $value;
	if ( ! $same ) {
		$report['options'][] = sprintf(
			'%s: %s -> %s',
			$key,
			array_key_exists( $key, $current ) ? json_encode( $current[ $key ] ) : '(absent)',
			json_encode( $value )
		);
		$current[ $key ] = $value;
		$changed         = true;
	}
}
if ( $mode === 'apply' && $changed ) {
	update_option( 'cmplz_options', $current );
}

// 2. The banner row, through the plugin's own save() so its sanitizers and
// its string registration (Polylang's WPML layer) run.
global $wpdb;
$table = $wpdb->prefix . 'cmplz_cookiebanners';
$row   = $wpdb->get_row( "SELECT * FROM $table WHERE `default` = 1 ORDER BY ID LIMIT 1", ARRAY_A );
if ( $row === null ) {
	$report['errors'][] = 'no default cookie banner row';
} else {
	$row    = array_map( 'maybe_unserialize', $row );
	$banner = new CMPLZ_COOKIEBANNER( (int) $row['ID'] );
	$differ = false;
	foreach ( $plan['banner'] as $field => $value ) {
		$current_value = isset( $row[ $field ] ) ? $row[ $field ] : null;
		if ( $current_value == $value ) {
			continue;
		}
		$differ             = true;
		$report['banner'][] = sprintf( '%s: %s -> %s', $field, json_encode( $current_value ), json_encode( $value ) );
		$banner->{$field}   = $value;
	}
	if ( $mode === 'apply' && $differ ) {
		$banner->save();
		$report['banner'][] = 'saved (banner_version ' . $banner->banner_version . ')';
	}
}

// 3. The German banner strings into Polylang's string translations.
if ( function_exists( 'PLL' ) ) {
	$lang = PLL()->model->get_language( 'de' );
	$mo   = new PLL_MO();
	$mo->import_from_db( $lang );
	foreach ( $plan['banner_de_strings'] as $source => $translation ) {
		if ( $mo->translate_if_any( (string) $source ) === $translation ) {
			continue;
		}
		$report['strings'][] = substr( $source, 0, 40 ) . '…';
		if ( $mode === 'apply' ) {
			$mo->add_entry( $mo->make_entry( (string) $source, $translation ) );
		}
	}
	if ( $mode === 'apply' && $report['strings'] ) {
		$mo->export_to_db( $lang );
	}
} else {
	$report['errors'][] = 'Polylang is not active: the German banner strings cannot be stored';
}

echo json_encode( $report );
"""


class WP:
    """WP-CLI, as a command prefix (the 68-contact-form.py wrapper)."""

    def __init__(self, command: str, user: str | None) -> None:
        self.prefix = shlex.split(command)
        self.user = user

    def run(self, *args: str, stdin: str | None = None, as_user: bool = False) -> str:
        command = [*self.prefix, *args]
        if as_user and self.user:
            command.append(f"--user={self.user}")
        result = subprocess.run(
            command, input=stdin, capture_output=True, text=True, check=False
        )
        if result.returncode != 0:
            raise SystemExit(
                f"wp {' '.join(args[:3])} failed:\n{result.stderr.strip()}"
            )
        lines = result.stdout.splitlines()
        return "\n".join(line for line in lines if not PHP_DIAGNOSTIC.match(line))

    def json(self, *args: str, stdin: str | None = None, as_user: bool = False) -> Any:
        out = self.run(*args, stdin=stdin, as_user=as_user)
        start = min((i for i in (out.find("["), out.find("{")) if i >= 0), default=-1)
        return json.loads(out[start:]) if start >= 0 else None

    def eval_php(self, code: str, as_user: bool = False) -> Any:
        return self.json("eval", code, as_user=as_user)


def plan_data(path: Path | None = None) -> dict[str, Any]:
    with (path or PLAN_PATH).open(encoding="utf-8") as handle:
        data: dict[str, Any] = json.load(handle)
        return data


def complianz(wp: WP, plan: dict[str, Any], mode: str) -> dict[str, Any]:
    code = (
        "$cmplz_plan = json_decode( <<<'JSON'\n"
        + json.dumps(plan)
        + "\nJSON, true );\n"
        + f"$cmplz_mode = '{mode}';\n"
        + COMPLIANZ_PHP
    )
    report = wp.eval_php(code, as_user=True)
    if not isinstance(report, dict):
        raise SystemExit("the Complianz step returned nothing readable")
    return report


def planned_privacy(content: str, language: dict[str, str]) -> tuple[str, list[str]]:
    """The new page content and the changes it makes, or the reason it refuses."""
    changes: list[str] = []
    new = content
    if language["cookies_new"] not in new:
        if language["cookies_old"] not in new:
            raise SystemExit(
                "the Cookies section matches neither the old sentence nor the new "
                "one; nothing is written"
            )
        new = new.replace(language["cookies_old"], language["cookies_new"], 1)
        changes.append("Cookies: the 'no analytics' sentence -> the consent sentence")
    if language["caption_new"] not in new:
        if language["caption_old"] not in new:
            raise SystemExit(
                "the processor table's caption matches neither the old nor the new "
                "one; nothing is written"
            )
        new = new.replace(language["caption_old"], language["caption_new"], 1)
        changes.append("Recipients: the caption names the measuring purpose")
    if language["google_row"].strip() not in new:
        anchor = re.compile(language["vies_row"], re.S)
        match = anchor.search(new)
        if not match:
            raise SystemExit(
                "the VIES row (the processor table's last fixed row) is missing; "
                "nothing is written"
            )
        new = new[: match.end()] + "\n" + language["google_row"] + new[match.end() :]
        changes.append("Recipients: Google joined the processor table")
    return new, changes


def read_post(wp: WP, post_id: int) -> str:
    content = wp.run("post", "get", str(post_id), "--field=post_content")
    if not content.strip():
        raise SystemExit(f"post {post_id}: content not readable")
    return content


def report_lines(report: dict[str, Any], *, drift: bool) -> bool:
    """Prints one report; returns True when something needs attention."""
    attention = False
    for section in ("options", "banner", "strings"):
        lines = report[section]
        if not lines:
            print(f"{section}: nothing to do", flush=True)
            continue
        attention = True
        for line in lines:
            print(f"{section}{' drifted' if drift else ''}: {line}", flush=True)
    for error in report["errors"]:
        print(f"error: {error}", flush=True)
        attention = True
    return attention


def do_plan(plan: dict[str, Any], wp: WP) -> int:
    report = complianz(wp, plan, "plan")
    attention = report_lines(report, drift=False)
    for name, language in plan["privacy"].items():
        content = read_post(wp, language["post_id"])
        _, changes = planned_privacy(content, language)
        state = "; ".join(changes) if changes else "nothing to do"
        print(f"privacy-{name} #{language['post_id']}: {state}", flush=True)
    return 1 if attention and report["errors"] else 0


def do_apply(plan: dict[str, Any], wp: WP, write: bool) -> int:
    report = complianz(wp, plan, "apply" if write else "plan")
    report_lines(report, drift=False)
    for name, language in plan["privacy"].items():
        post_id = language["post_id"]
        new, changes = planned_privacy(read_post(wp, post_id), language)
        print(
            f"privacy-{name} #{post_id}: "
            + ("; ".join(changes) if changes else "nothing to do"),
            flush=True,
        )
        if write and changes:
            wp.run("post", "update", str(post_id), "-", stdin=new, as_user=True)
    if not write:
        print("\ndry run: nothing written (add --write)", flush=True)
    return 1 if report["errors"] else 0


def do_verify(plan: dict[str, Any], wp: WP, base: str) -> int:
    ok = not report_lines(complianz(wp, plan, "plan"), drift=True)
    for name, language in plan["privacy"].items():
        try:
            _, changes = planned_privacy(read_post(wp, language["post_id"]), language)
        except SystemExit as refusal:
            print(f"privacy-{name}: {refusal}", flush=True)
            ok = False
            continue
        if changes:
            print(f"privacy-{name}: still to apply: {'; '.join(changes)}", flush=True)
            ok = False
    if base:
        ok = verify_rendered(plan, base) and ok
    print("ok" if ok else "not ok", flush=True)
    return 0 if ok else 1


def verify_rendered(plan: dict[str, Any], base: str) -> bool:
    """The rendered pages: the banner with its two first-layer buttons, and the
    footer entry the LC partial carries (installed by `present`)."""
    ok = True
    for path, language in (("/", "en"), ("/de/", "de")):
        try:
            with urllib.request.urlopen(
                base.rstrip("/") + path, timeout=60
            ) as response:
                html = response.read().decode("utf-8", "replace")
        except Exception as error:  # noqa: BLE001 - the report carries the reason.
            print(f"{path}: {error}", flush=True)
            ok = False
            continue
        label = re.escape(plan["footer"][language]["label"])
        banner = "cmplz-cookiebanner" in html
        entry = (
            re.search(
                r'<button[^>]+class="[^"]*cmplz-manage-consent[^"]*"[^>]*>' + label,
                html,
            )
            is not None
        )
        accept = '<button class="cmplz-btn cmplz-accept' in html
        deny = '<button class="cmplz-btn cmplz-deny' in html
        print(
            f"{path}: banner={banner} footer-entry={entry} accept={accept} deny={deny}",
            flush=True,
        )
        ok = ok and banner and entry and accept and deny
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--wp", required=True, help="WP-CLI command, e.g. ~/de-linker-local/t201/wp.sh"
    )
    parser.add_argument(
        "--user", default=None, help="administrator login for the writes"
    )
    parser.add_argument(
        "--base",
        default="",
        help="instance address for verify's rendered check "
        "(e.g. http://127.0.0.1:9051); empty skips it",
    )
    parser.add_argument(
        "--plan", default=None, help="the data file (default: 201-consent.json)"
    )
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("plan", help="report what would change")
    apply_parser = subparsers.add_parser(
        "apply", help="write (needs --write, otherwise a dry run)"
    )
    apply_parser.add_argument("--write", action="store_true")
    subparsers.add_parser("verify", help="read back: 0 when the surface is in place")
    args = parser.parse_args()

    path = Path(args.plan).resolve() if args.plan else None
    plan = plan_data(path)
    wp = WP(args.wp, args.user)

    if args.command == "plan":
        return do_plan(plan, wp)
    if args.command == "apply":
        return do_apply(plan, wp, args.write)
    return do_verify(plan, wp, args.base)


if __name__ == "__main__":
    sys.exit(main())
