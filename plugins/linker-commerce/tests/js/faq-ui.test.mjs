import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { test } from 'node:test';
const require = createRequire(import.meta.url);
const {matches} = require('../../assets/faq-ui.js');
const {JSDOM} = require('../../../linker-tools/node_modules/jsdom');
test('FAQ filter supports multiple words, case, accents and empty reset', () => {
 assert.equal(matches('GoodWe inverter 10 kW', 'GOODWE 10'), true);
 assert.equal(matches('Lösungsentwurf hinzufügen', 'losungsentwurf'), true);
 assert.equal(matches('GoodWe inverter 10 kW', 'GoodWe battery'), false);
 assert.equal(matches('Anything', '  '), true);
});
test('enhancement preserves initial count, filters groups, restores user open state', () => {
 const dom = new JSDOM(`<div id="linker-faq-page"><div data-faq-search hidden><input><p data-faq-result data-result-label="Matching questions: %d" data-empty-label="No matches"></p></div><details class="linker-answers-group"><summary>A</summary><details class="linker-answer"><summary>Battery?</summary><div>GoodWe 10 kWh</div></details></details><section class="linker-trade-category"><details class="linker-trade-question"><summary>Account?</summary><div>Approval</div></details></section><details class="linker-documents-group"><summary>Files</summary><li class="linker-document">GoodWe manual</li></details></div>`, {runScripts:'outside-only'});
 const {window} = dom; const root=window.document;
 const group=root.querySelector('.linker-answers-group'); group.open=true;
 window.eval(readFileSync(new URL('../../assets/faq-ui.js',import.meta.url),'utf8'));
 assert.equal(root.querySelector('[data-faq-search]').hidden,false);
 assert.equal(root.querySelectorAll('.linker-answer,.linker-trade-question').length,2);
 const input=root.querySelector('input'); input.value='GoodWe'; input.dispatchEvent(new window.Event('input'));
 assert.equal(root.querySelector('.linker-trade-category').hidden,true);
 assert.equal(group.open,true);
 input.value='manual';input.dispatchEvent(new window.Event('input'));
 assert.equal(root.querySelector('[data-faq-result]').textContent,'Matching questions: 1');
 input.value='zzzz';input.dispatchEvent(new window.Event('input'));
 assert.equal(root.querySelector('[data-faq-result]').textContent,'No matches');
 input.value='';input.dispatchEvent(new window.Event('input'));
 assert.equal(group.open,true);
 assert.equal(root.querySelector('.linker-trade-category').hidden,false);
 assert.equal(root.querySelector('.linker-documents-group').open,false);
});
