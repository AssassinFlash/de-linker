/**
 * Publication evidence distinguishes ready engineering inputs from sale products.
 *
 * @covers \Linker\Commerce\Products\EngineeringReference
 * @covers \Linker\Commerce\Products\EngineeringFeed
 * @covers \Linker\Commerce\Products\Publication\Visibility
