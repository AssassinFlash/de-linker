		WP_Mock::userFunction( 'taxonomy_exists' )->andReturn( true );
		$before = $this->current_faq_meta;
		$result = ReferenceMigration::run(
			array(
				'overlay' => array(
					array(
						'id'        => 'mat_fixture_module',
